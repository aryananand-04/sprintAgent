/**
 * Generates supabase/seed.sql from the demo data in src/data (single source of truth).
 * IDs become deterministic UUIDs via md5(); timestamps become relative to now() so the
 * demo sprint is always mid-flight after `supabase db reset`.
 *
 * Run: npm run db:seed:gen
 */
import { writeFileSync } from 'node:fs'
import { INITIAL_TASKS } from '../src/data/tasks'
import { TEAM } from '../src/data/team'
import { SPRINT, INITIAL_ESCALATIONS, INITIAL_FEED, INITIAL_SPRINT_HISTORY } from '../src/data/sprint'

const NOW = Date.now()
const WS = 'demo-workspace'

const q = (v: string | null | undefined) => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`)
const uid = (key: string) => `md5(${q(key)})::uuid`
const arr = (xs: readonly string[] | undefined, type = 'text') =>
  xs && xs.length ? `array[${xs.map(q).join(', ')}]::${type}[]` : `'{}'::${type}[]`
const ago = (iso: string) => {
  // Minute precision keeps the output stable between runs (CI checks it for drift).
  const mins = Math.max(0, Math.round((NOW - new Date(iso).getTime()) / 60_000))
  return `now() - interval '${mins} minutes'`
}
const num = (n: number | undefined | null) => (n == null ? 'null' : String(n))
const bool = (b: boolean | undefined) => (b ? 'true' : 'false')

const taskIds = new Set(INITIAL_TASKS.map((t) => t.id))

/* ── Demo users (local only; password: password123) ─────────────────── */
const USERS = [
  { key: 'user-admin', email: 'admin@demo.sprintagent.dev', name: 'Demo Admin', role: 'admin', member: null },
  { key: 'user-pm', email: 'pm@demo.sprintagent.dev', name: 'Demo PM', role: 'pm', member: null },
  { key: 'user-contrib', email: 'dev@demo.sprintagent.dev', name: 'Arjun Nair', role: 'contributor', member: 'arjun' },
  { key: 'user-viewer', email: 'viewer@demo.sprintagent.dev', name: 'Demo Viewer', role: 'viewer', member: null },
] as const

const out: string[] = [
  '-- GENERATED by scripts/generate-seed.ts — do not edit by hand.',
  '-- Local development seed. Demo users use password: password123',
  '',
]

for (const u of USERS) {
  out.push(
    `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token,
  email_change_token_new, email_change)
values ('00000000-0000-0000-0000-000000000000', ${uid(u.key)}, 'authenticated', 'authenticated', ${q(u.email)},
  crypt('password123', gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}',
  ${q(JSON.stringify({ full_name: u.name }))}, now(), now(), '', '', '', '');`,
    `insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (${uid(u.key + '-identity')}, ${uid(u.key)}, ${uid(u.key)}::text,
  jsonb_build_object('sub', ${uid(u.key)}::text, 'email', ${q(u.email)}, 'email_verified', true),
  'email', now(), now(), now());`,
  )
}

/* ── Workspace ──────────────────────────────────────────────────────── */
out.push(
  '',
  `insert into public.workspaces (id, name, slug, created_by) values (${uid(WS)}, 'Acme Checkout', 'acme-demo', ${uid('user-admin')});`,
  ...USERS.map(
    (u) => `insert into public.workspace_members (workspace_id, user_id, role) values (${uid(WS)}, ${uid(u.key)}, '${u.role}');`,
  ),
  `insert into public.autonomy_policies (workspace_id, updated_by) values (${uid(WS)}, ${uid('user-admin')});`,
  `insert into public.calibration (workspace_id, decision) select ${uid(WS)}, d from unnest(enum_range(null::public.agent_decision)) d;`,
  '',
)

/* ── Team ───────────────────────────────────────────────────────────── */
for (const m of TEAM) {
  const linked = USERS.find((u) => u.member === m.id)
  out.push(
    `insert into public.team_members (id, workspace_id, user_id, name, initials, title, skills, current_load, capacity, color)
values (${uid(m.id)}, ${uid(WS)}, ${linked ? uid(linked.key) : 'null'}, ${q(m.name)}, ${q(m.initials)}, ${q(m.role)},
  ${arr(m.skills)}, ${m.currentLoad}, ${m.capacity}, ${q(m.color)});`,
  )
}

/* ── Sprints: active (relative dates) + archived history ───────────── */
out.push(
  '',
  // completed_points is maintained by the tasks_completion trigger from done tasks.
  `insert into public.sprints (id, workspace_id, name, goal, status, start_date, end_date, total_points,
  committed_points, velocity, health, created_at)
values (${uid(SPRINT.id)}, ${uid(WS)}, ${q(SPRINT.name)}, ${q(SPRINT.goal)}, 'active', current_date - 7, current_date + 7,
  ${SPRINT.totalPoints}, ${SPRINT.committedPoints}, ${SPRINT.velocity}, '${SPRINT.health}', now() - interval '8 days');`,
)
for (const s of INITIAL_SPRINT_HISTORY) {
  const end = `(${ago(s.endDate)})::date`
  out.push(
    `insert into public.sprints (id, workspace_id, name, goal, status, start_date, end_date, committed_points,
  completed_points, velocity, health, snapshot)
values (${uid(s.id)}, ${uid(WS)}, ${q(s.name)}, ${q(s.goal)}, 'archived', ${end} - 14, ${end}, ${s.committedPoints},
  ${s.completedPoints}, ${s.velocity}, '${s.health}',
  ${q(JSON.stringify({ taskCount: s.taskCount, doneCount: s.doneCount, escalationCount: s.escalationCount }))}::jsonb);`,
  )
}

/* ── Tasks ──────────────────────────────────────────────────────────── */
out.push('')
let doneIndex = 0
for (const t of INITIAL_TASKS) {
  // Spread completions over the first week of the sprint so the burndown has a shape.
  const completedAt = t.status === 'done' ? `now() - interval '${6 - (doneIndex++ % 6)} days'` : 'null'
  const external = t.externalBlockers
  out.push(
    `insert into public.tasks (id, workspace_id, sprint_id, title, description, type, status, urgency, impact, effort,
  risk, clarity, assignee_id, external_blockers, source, story_points, tags, decision, decision_reason, triage_score,
  confidence, is_ai_triaged, is_ad_hoc, completed_at, created_at)
values (${uid(t.id)}, ${uid(WS)}, ${uid(SPRINT.id)}, ${q(t.title)}, ${q(t.description)}, '${t.type}', '${t.status}',
  '${t.urgency}', ${t.impact}, ${t.effort}, ${t.risk}, ${t.clarity}, ${t.assigneeId ? uid(t.assigneeId) : 'null'},
  ${arr(external)}, ${q(t.source)}, ${num(t.storyPoints)}, ${arr(t.tags)}, ${t.decision ? `'${t.decision}'` : 'null'},
  ${q(t.decisionReason)}, ${num(t.triageScore)}, ${num(t.confidence)}, ${bool(t.isAITriaged)}, ${bool(t.isAdHoc)},
  ${completedAt}, ${ago(t.createdAt)});`,
  )
}
for (const t of INITIAL_TASKS) {
  for (const d of t.dependencies) {
    out.push(
      `insert into public.task_dependencies (workspace_id, task_id, depends_on_task_id) values (${uid(WS)}, ${uid(t.id)}, ${uid(d)});`,
    )
  }
}

/* ── Escalations & feed ─────────────────────────────────────────────── */
out.push('')
for (const e of INITIAL_ESCALATIONS) {
  out.push(
    `insert into public.escalations (id, workspace_id, task_id, task_title, reason, recommendation, urgency, category,
  resolved_at, created_at)
values (${uid(e.id)}, ${uid(WS)}, ${taskIds.has(e.taskId) ? uid(e.taskId) : 'null'}, ${q(e.taskTitle)}, ${q(e.reason)},
  ${q(e.recommendation)}, '${e.urgency}', '${e.category}', ${e.resolved ? 'now()' : 'null'}, ${ago(e.createdAt)});`,
  )
}
for (const f of INITIAL_FEED) {
  out.push(
    `insert into public.feed_events (id, workspace_id, type, message, task_id, member_id, decision, created_at)
values (${uid(f.id)}, ${uid(WS)}, '${f.type}', ${q(f.message)}, ${f.taskId && taskIds.has(f.taskId) ? uid(f.taskId) : 'null'},
  ${f.memberId && TEAM.some((m) => m.id === f.memberId) ? uid(f.memberId) : 'null'},
  ${f.decision ? `'${f.decision}'` : 'null'}, ${ago(f.timestamp)});`,
  )
}

writeFileSync('supabase/seed.sql', out.join('\n') + '\n')
console.log(`seed.sql: ${TEAM.length} team, ${INITIAL_TASKS.length} tasks, ${INITIAL_ESCALATIONS.length} escalations, ${INITIAL_FEED.length} feed events`)
